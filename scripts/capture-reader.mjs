// Local visual QA only. Pages are schematic test charts, never a production fallback.
import { chromium } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import { readerServer } from '../tests/helpers/reader-server.ts'
const base = process.env.QA_BASE_URL || 'http://127.0.0.1:5180'
const output = process.env.QA_OUTPUT || '/data/reader-qa'
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, args: ['--no-sandbox'] })
const errors = []
try {
  for (const [size, width, height] of [['mobile', 390, 844], ['desktop', 1440, 1000]]) {
    const context = await browser.newContext({ viewport: { width, height }, colorScheme: 'light' })
    const page = await context.newPage()
    page.on('pageerror', e => errors.push(e.message))
    await readerServer(page)
    async function capture(name) {
      await page.evaluate(() => document.fonts.ready)
      await page.waitForTimeout(250)
      await page.screenshot({ path: `${output}/${size}-${name}.png`, fullPage: true, animations: 'disabled' })
      if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw Error(`Overflow in ${size}/${name}`)
      if (!await page.evaluate(() => document.fonts.check('24px "Material Symbols Rounded"'))) throw Error('Icon font missing')
    }
    await page.goto(`${base}/manga/1`)
    await page.getByRole('link', { name: 'Start reading', exact: true }).waitFor()
    await capture('manga')
    await page.getByRole('link', { name: 'Start reading', exact: true }).click()
    await page.getByRole('img', { name: 'Page 1 of 3', exact: true }).waitFor()
    await capture('reader')
    await page.getByRole('button', { name: 'Toggle reading controls' }).click()
    await capture('immersive')
    await page.getByRole('button', { name: 'Show reading controls' }).click()
    await page.getByRole('button', { name: 'Reader settings', exact: true }).click()
    await capture('settings-reading')
    await page.getByRole('combobox', { name: 'Reading mode', exact: true }).press('Enter')
    await capture('reading-mode-menu')
    await page.getByRole('option', { name: 'Right to left', exact: true }).click()
    await page.getByRole('tab', { name: 'General', exact: true }).click()
    await capture('settings-general')
    await page.getByRole('button', { name: 'Done', exact: true }).click()
    await capture('rtl')
    await page.getByRole('button', { name: 'Chapter list', exact: true }).click()
    await capture('chapter-list')
    await page.getByRole('button', { name: 'Close chapter list', exact: true }).click()
    await page.getByRole('button', { name: 'Reader settings', exact: true }).click()
    await page.getByRole('tab', { name: 'Reading', exact: true }).click()
    await page.getByRole('combobox', { name: 'Reading mode', exact: true }).press('Enter')
    await page.getByRole('option', { name: 'Webtoon · vertical scroll', exact: true }).click()
    await page.getByRole('button', { name: 'Done', exact: true }).click()
    await capture('webtoon')
    await page.getByRole('button', { name: 'Reader settings', exact: true }).click()
    await page.getByRole('combobox', { name: 'Reading mode', exact: true }).press('Enter')
    await page.getByRole('option', { name: 'Left to right', exact: true }).click()
    await page.getByRole('combobox', { name: 'Image scale', exact: true }).press('Enter')
    await page.getByRole('option', { name: 'Fit width', exact: true }).click()
    await page.getByRole('combobox', { name: 'Reader background', exact: true }).press('Enter')
    await page.getByRole('option', { name: 'Paper', exact: true }).click()
    await page.getByRole('button', { name: 'Done', exact: true }).click()
    await capture('fit-width-paper')
    await page.getByRole('button', { name: 'Toggle reading controls' }).click()
    await capture('fit-width-immersive')
    await page.getByRole('button', { name: 'Show reading controls' }).click()
    await page.unroute('**/api/v1/**')
    await page.evaluate(() => localStorage.setItem('mihon.reader.mode', 'ltr'))
    await readerServer(page, { pageFailure: true })
    await page.reload()
    await page.getByRole('button', { name: 'Next page', exact: true }).click()
    await page.getByRole('button', { name: 'Next page', exact: true }).click()
    await page.getByRole('heading', { name: 'Page 3 could not load' }).waitFor()
    await capture('page-error')
    await page.unroute('**/api/v1/**')
    await readerServer(page, { apiFailure: true })
    await page.reload()
    await page.getByRole('heading', { name: 'Unable to open chapter' }).waitFor()
    await capture('chapter-error')
    await page.unroute('**/api/v1/**')
    await readerServer(page, { noPages: true })
    await page.reload()
    await page.getByRole('heading', { name: 'No pages returned' }).waitFor()
    await capture('no-pages')
    await context.close()
  }
} finally { await browser.close() }
if (errors.length) throw Error(errors.join('\n'))
console.log('Captured 28 reader/manga states without page exceptions or horizontal overflow.')
