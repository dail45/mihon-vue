/**
 * Generates src/theme/appThemes.ts from the pinned Mihon reference color schemes.
 *
 * Source: mihon/app/src/main/java/eu/kanade/presentation/theme/colorscheme/*.kt
 * (pinned commit 446f6df82c390ab760802c2fce3b677bce3f31c1)
 *
 * Run: node scripts/generate-app-themes.mjs
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { join, dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const schemeDir = join(root, 'mihon', 'app', 'src', 'main', 'java', 'eu', 'kanade', 'presentation', 'theme', 'colorscheme')

/** AppTheme enum order and titles, from AppTheme.kt. */
const appThemes = [
  ['default', 'Default', 'TachiyomiColorScheme.kt'],
  ['catppuccin', 'Catppuccin', 'CatppuccinColorScheme.kt'],
  ['greenApple', 'Green Apple', 'GreenAppleColorScheme.kt'],
  ['lavender', 'Lavender', 'LavenderColorScheme.kt'],
  ['midnightDusk', 'Midnight Dusk', 'MidnightDuskColorScheme.kt'],
  ['nord', 'Nord', 'NordColorScheme.kt'],
  ['strawberryDaiquiri', 'Strawberry Daiquiri', 'StrawberryColorScheme.kt'],
  ['tako', 'Tako', 'TakoColorScheme.kt'],
  ['tealTurquoise', 'Teal & Turquoise', 'TealTurqoiseColorScheme.kt'],
  ['tidalWave', 'Tidal Wave', 'TidalWaveColorScheme.kt'],
  ['yinYang', 'Yin & Yang', 'YinYangColorScheme.kt'],
  ['yotsuba', 'Yotsuba', 'YotsubaColorScheme.kt'],
  ['tokyoNight', 'Tokyo Night', 'TokyoNightColorScheme.kt'],
  ['monochrome', 'Monochrome', 'MonochromeColorScheme.kt'],
]

function parseScheme(file) {
  const text = readFileSync(join(schemeDir, file), 'utf8')
  const out = { light: {}, dark: {} }
  const re = /override val (darkScheme|lightScheme) = (?:dark|light)ColorScheme\(/g
  let m
  while ((m = re.exec(text)) !== null) {
    const which = m[1] === 'darkScheme' ? 'dark' : 'light'
    // Match the closing parenthesis of the ColorScheme call.
    let depth = 1
    let i = m.index + m[0].length
    while (i < text.length && depth > 0) {
      const ch = text[i]
      if (ch === '(') depth++
      else if (ch === ')') depth--
      i++
    }
    const body = text.slice(m.index + m[0].length, i - 1)
    for (const c of body.matchAll(/(\w+)\s*=\s*Color\(0x([0-9A-Fa-f]{8})\)/g)) {
      out[which][c[1]] = `#${c[2].slice(2)}`.toUpperCase()
    }
  }
  return out
}

const missing = new Set()
const themes = appThemes.map(([id, title, file]) => {
  const s = parseScheme(file)
  for (const which of ['light', 'dark']) {
    for (const key of Object.keys(s.light)) {
      if (!(key in s[which])) missing.add(`${file}:${which}:${key}`)
    }
  }
  return { id, title, light: s.light, dark: s.dark }
})

if (missing.size) console.error('missing keys:\n' + [...missing].join('\n'))

const order = ['primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer', 'inversePrimary',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'error', 'onError', 'errorContainer', 'onErrorContainer',
  'background', 'onBackground', 'surface', 'onSurface', 'surfaceVariant', 'onSurfaceVariant',
  'surfaceTint', 'inverseSurface', 'inverseOnSurface', 'outline', 'outlineVariant',
  'surfaceContainerLowest', 'surfaceContainerLow', 'surfaceContainer', 'surfaceContainerHigh', 'surfaceContainerHighest']

function block(colors) {
  const keys = order.filter(k => k in colors)
  const extra = Object.keys(colors).filter(k => !order.includes(k))
  const lines = [...keys, ...extra].map(k => `        ${k}: '${colors[k]}',`)
  return `{\n${lines.join('\n')}\n      }`
}

const body = themes.map(t => `  {
    id: '${t.id}',
    title: '${t.title}',
    light: ${block(t.light)},
    dark: ${block(t.dark)},
  },`).join('\n')

const out = `// GENERATED by scripts/generate-app-themes.mjs — do not edit by hand.
// Source: mihon/app/src/main/java/eu/kanade/presentation/theme/colorscheme/*.kt
// (Mihon commit 446f6df82c390ab760802c2fce3b677bce3f31c1)
export type AppThemeColors = Record<string, string>

export interface AppTheme {
  id: string
  title: string
  light: AppThemeColors
  dark: AppThemeColors
}

export const appThemes: AppTheme[] = [
${body}
]
`
writeFileSync(join(root, 'src', 'theme', 'appThemes.ts'), out)
console.log(`wrote ${themes.length} themes`)
