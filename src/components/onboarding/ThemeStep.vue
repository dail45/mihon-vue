/** `isComplete` of the reference step: always true (ThemeStep.kt:16). */
defineModel<boolean>('complete', { default: true })

/** Selected app theme (`AppTheme` enum name). */
const appTheme = defineModel<string>('appTheme', { default: 'DEFAULT' })

/** `uiPreferences.themeDarkAmoled`; only affects the dark previews. */
const amoled = defineModel<boolean>('amoled', { default: false })

/** Optional two-way binding for themeMode (defaults to syncing with store). */
const modelThemeMode = defineModel<ThemeMode>('themeMode')
const currentThemeMode = computed<ThemeMode>({
  get: () => modelThemeMode.value ?? preferences.themeMode,
  set: (val: ThemeMode) => {
    if (modelThemeMode.value !== undefined) {
      modelThemeMode.value = val
    }
    preferences.themeMode = val
  },
})

/** `mihon.appTheme` local preference key (no server state, no credentials). */
const APP_THEME_KEY = 'mihon.appTheme'
const AMOLED_KEY = 'mihon.themeDarkAmoled'

function readLocal(key: string): string | null {
  try { return localStorage.getItem(key) } catch { return null }
}
function writeLocal(key: string, value: string) {
  try { localStorage.setItem(key, value) } catch { /* private mode: session-only preference */ }
}

let storedTheme = readLocal(APP_THEME_KEY)
if (!storedTheme) {
  const appPref = readLocal('mihon.appearance.appTheme')
  if (appPref && THEME_ID_TO_ENUM[appPref]) storedTheme = THEME_ID_TO_ENUM[appPref]
}
if (storedTheme && findAppThemeScheme(storedTheme)) appTheme.value = storedTheme
let storedAmoled = readLocal(AMOLED_KEY)
if (storedAmoled === null) {
  const prefAmoled = readLocal('mihon.appearance.amoled')
  if (prefAmoled !== null) storedAmoled = prefAmoled
}
if (storedAmoled !== null) amoled.value = storedAmoled === 'true'

watch(appTheme, value => {
  writeLocal(APP_THEME_KEY, value)
  try {
    const id = ENUM_TO_THEME_ID[value] || value.toLowerCase()
    localStorage.setItem('mihon.appearance.appTheme', id)
  } catch { /* private mode */ }
})
watch(amoled, value => {
  writeLocal(AMOLED_KEY, String(value))
  try {
    localStorage.setItem('mihon.appearance.amoled', String(value))
  } catch { /* private mode */ }
})

/** `MultiChoiceSegmentedButtonRow` options (AppThemeModePreferenceWidget.kt:15-19). */
const themeModes: { value: ThemeMode; label: string }[] = [
  { value: 'system', label: 'System' },
  { value: 'light', label: 'Light' },
  { value: 'dark', label: 'Dark' },
]

/**
 * The reference resolves the light/dark variant from `isSystemInDarkTheme()`
 * (TachiyomiTheme.kt:58), which in the Android app follows the *app theme mode*
 * (light / dark / system) because `setAppCompatDelegateThemeMode` drives the night mode.
 * The web client resolves it the same way as src/App.vue does.
 */
const systemDark = ref(
  typeof window !== 'undefined' && window.matchMedia
    ? window.matchMedia('(prefers-color-scheme: dark)').matches
    : false,
)
let media: MediaQueryList | null = null
function onSystemThemeChange(event: MediaQueryListEvent) { systemDark.value = event.matches }
onMounted(() => {
  if (typeof window !== 'undefined' && window.matchMedia) {
    media = window.matchMedia('(prefers-color-scheme: dark)')
    systemDark.value = media.matches
    media.addEventListener('change', onSystemThemeChange)
  }
})
onBeforeUnmount(() => media?.removeEventListener('change', onSystemThemeChange))

const dark = computed(
  () => currentThemeMode.value === 'dark' || (currentThemeMode.value === 'system' && systemDark.value),
)

/** Convert camelCase color token keys to Vuetify kebab-case color keys. */
function toVuetifyColors(palette: AppThemeColors): Record<string, string> {
  const result: Record<string, string> = {}
  for (const [key, value] of Object.entries(palette)) {
    const kebab = key.replace(/[A-Z]/g, match => `-${match.toLowerCase()}`)
    result[kebab] = value
  }
  return result
}

/**
 * The reference applies the picked app theme by recreating the activity
 * (`ActivityCompat.recreate`, AppThemePreferenceWidget.kt:104), which re-renders the whole app with
 * the new color scheme. The web client does the same by registering a Vuetify theme for the picked
 * scheme and switching to it.
 */
let vuetifyTheme: ReturnType<typeof useTheme> | null = null
try {
  vuetifyTheme = useTheme()
} catch {
  // Headless test runner without Vuetify context
}

function vuetifyThemeName(scheme: AppThemeScheme): string {
  return `mihon-app-${scheme.name.toLowerCase()}-${dark.value ? 'dark' : 'light'}`
}

function registerVuetifyThemes() {
  if (!vuetifyTheme) return
  const themes = vuetifyTheme.themes.value as Record<string, unknown>
  for (const scheme of APP_THEME_SCHEMES) {
    if (scheme.unsupported) continue
    const lightName = `mihon-app-${scheme.name.toLowerCase()}-light`
    const darkName = `mihon-app-${scheme.name.toLowerCase()}-dark`
    themes[lightName] = { dark: false, colors: toVuetifyColors(scheme.light) }
    themes[darkName] = { dark: true, colors: toVuetifyColors(scheme.dark) }
  }
}

function applyAppTheme() {
  if (!vuetifyTheme) return
  const scheme = findAppThemeScheme(appTheme.value)
  if (!scheme || scheme.unsupported) return
  const name = vuetifyThemeName(scheme)
  const palette = paletteOf(scheme)
  const themes = vuetifyTheme.themes.value as Record<string, unknown>
  themes[name] = {
    dark: dark.value,
    colors: toVuetifyColors(palette),
  }
  void vuetifyTheme.change(name)
}

onMounted(() => {
  registerVuetifyThemes()
  applyAppTheme()
})

watch([appTheme, dark, amoled], () => {
  applyAppTheme()
})

/** AMOLED overrides of the dark scheme (BaseColorScheme.kt:26-42). */
const AMOLED_BACKGROUND = '#000000'
const AMOLED_SURFACE_CONTAINER = '#0C0C0C'

/** MD3 defaults for the roles a scheme leaves unset. */
const DEFAULT_OUTLINE_VARIANT_LIGHT = '#CAC4D0'
const DEFAULT_OUTLINE_VARIANT_DARK = '#49454F'

function paletteOf(scheme: AppThemeScheme): AppThemeColors {
  const base: AppThemeColors = dark.value ? scheme.dark : scheme.light
  const outlineVariant = base.outlineVariant
    ?? (dark.value ? DEFAULT_OUTLINE_VARIANT_DARK : DEFAULT_OUTLINE_VARIANT_LIGHT)
  const colors: AppThemeColors = { ...base, outlineVariant }
  if (!dark.value || !amoled.value) return colors
  // amoledScheme.copy(background = Black, onBackground = White, surface = Black, onSurface = White)
  // plus the overridden dark surface containers.
  colors.background = AMOLED_BACKGROUND
  colors.onSurface = '#FFFFFF'
  colors.surfaceContainer = AMOLED_SURFACE_CONTAINER
  return colors
}

/** Dialog shown when an unsupported theme entry is picked ("Dynamic"). */
const stubOpen = ref(false)
const stubTheme = ref<AppThemeScheme | null>(null)

function selectTheme(scheme: AppThemeScheme) {
  if (scheme.unsupported) {
    stubTheme.value = scheme
    stubOpen.value = true
    return
  }
  appTheme.value = scheme.name
}

const themes = computed(() => APP_THEME_SCHEMES.map(scheme => ({
  scheme,
  palette: paletteOf(scheme),
  selected: scheme.name === appTheme.value,
})))
