import { test, expect } from '@playwright/test'
import { readerServer } from '../helpers/reader-server'

test('manga launches actual chapter index; paged, RTL, keyboard, and chapter navigation work', async ({ page }) => {
  const server = await readerServer(page)
  await page.goto('/manga/1')
  await page.getByRole('link', { name: 'Start reading', exact: true }).click()
  await expect(page).toHaveURL(/\/read\/7$/)
  await expect(page.getByRole('img', { name: 'Page 1 of 3', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Next page', exact: true }).click()
  await expect(page.getByRole('img', { name: 'Page 2 of 3', exact: true })).toBeVisible()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('img', { name: 'Page 3 of 3', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Reader settings', exact: true }).click()
  await page.getByRole('combobox', { name: 'Reading mode', exact: true }).press('Enter')
  await page.getByRole('option', { name: 'Right to left', exact: true }).click()
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('img', { name: 'Page 2 of 3', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Toggle reading controls' }).click()
  await expect(page.getByRole('button', { name: 'Reader settings', exact: true })).toBeHidden()
  await page.getByRole('button', { name: 'Show reading controls', exact: true }).click()
  await page.getByRole('button', { name: 'Chapter list', exact: true }).click()
  await page.getByText('Chapter 2', { exact: true }).click()
  await expect(page).toHaveURL(/\/read\/9$/)
  await expect(page.getByRole('img', { name: 'Page 1 of 3', exact: true })).toBeVisible()
  expect(server.patches).toHaveLength(0)
  expect(server.imageRequests.every(url => new URL(url).searchParams.get('updateProgress') === 'false')).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('manual/opt-in autosave never marks an unsuccessful image as read', async ({ page }) => {
  const server = await readerServer(page, { pageFailure: true })
  await page.goto('/manga/1/read/7')
  await expect(page.getByRole('button', { name: 'Save current page on server' })).toBeEnabled()
  expect(server.patches).toHaveLength(0)
  await page.getByRole('button', { name: 'Save current page on server' }).click()
  await expect.poll(() => server.patches.length).toBe(1)
  expect(server.patches[0]).toEqual({ path: '/api/v1/manga/1/chapter/7', fields: { lastPageRead: '0' } })
  await page.getByRole('button', { name: 'Reader settings', exact: true }).click()
  await page.getByRole('tab', { name: 'General', exact: true }).click()
  await page.getByLabel('Automatically save reading progress').check()
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await page.getByRole('button', { name: 'Next page', exact: true }).click()
  await expect.poll(() => server.patches.some(p => p.fields.lastPageRead === '1')).toBe(true)
  await page.getByRole('button', { name: 'Next page', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Page 3 could not load' })).toBeVisible()
  expect(server.patches.some(p => p.fields.read === 'true')).toBe(false)
  await page.getByRole('button', { name: 'Retry page', exact: true }).click()
  await expect.poll(() => server.patches.some(p => p.fields.lastPageRead === '2' && p.fields.read === 'true')).toBe(true)
})

test('webtoon image preloading does not save unseen pages', async ({ page }) => {
  await page.addInitScript(() => { localStorage.setItem('mihon.reader.mode', 'webtoon'); localStorage.setItem('mihon.reader.saveProgress', 'true') })
  const server = await readerServer(page)
  await page.goto('/manga/1/read/7')
  await expect.poll(() => server.patches.some(p => p.fields.lastPageRead === '0')).toBe(true)
  await expect(page.getByRole('img', { name: 'Page 3 of 3', exact: true })).toBeAttached()
  expect(server.patches.some(p => p.fields.lastPageRead === '2')).toBe(false)
  await page.locator('.reader-viewport').evaluate(e => { e.scrollTop = e.scrollHeight })
  await expect.poll(() => server.patches.some(p => p.fields.lastPageRead === '2')).toBe(true)
})

test('reader API failure and zero-page response have honest states', async ({ page }) => {
  await readerServer(page, { apiFailure: true })
  await page.goto('/manga/1/read/7')
  await expect(page.getByRole('heading', { name: 'Unable to open chapter' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Back to manga', exact: true })).toBeVisible()
  await page.unroute('**/api/v1/**')
  await readerServer(page, { noPages: true })
  await page.reload()
  await expect(page.getByRole('heading', { name: 'No pages returned' })).toBeVisible()
})

test('touch navigation, mode changes, scaling preferences, and explicit bookmarks work', async ({ page }) => {
  const server = await readerServer(page)
  await page.goto('/manga/1/read/7')
  await expect(page.getByRole('img', { name: 'Page 1 of 3', exact: true })).toBeVisible()
  await page.locator('.reader-viewport').evaluate(el => {
    const start = new Event('touchstart', { bubbles: true })
    Object.defineProperty(start, 'touches', { value: [{ clientX: 300, clientY: 350 }] })
    el.dispatchEvent(start)
    const end = new Event('touchend', { bubbles: true })
    Object.defineProperty(end, 'changedTouches', { value: [{ clientX: 100, clientY: 350 }] })
    el.dispatchEvent(end)
  })
  await expect(page.getByRole('img', { name: 'Page 2 of 3', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Reader settings', exact: true }).click()
  await page.getByRole('combobox', { name: 'Reading mode', exact: true }).press('Enter')
  await page.getByRole('option', { name: 'Webtoon · vertical scroll', exact: true }).click()
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(page.locator('.reader-bottom').getByText('2 / 3', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Chapter bookmark actions', exact: true }).click()
  await page.getByText('Add bookmark on server', { exact: true }).click()
  await expect.poll(() => server.patches.some(p => p.fields.bookmarked === 'true')).toBe(true)
  await expect(page.getByText('Bookmark added on server', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Reader settings', exact: true }).click()
  await page.getByRole('combobox', { name: 'Reading mode', exact: true }).press('Enter')
  await page.getByRole('option', { name: 'Left to right', exact: true }).click()
  await page.getByRole('combobox', { name: 'Image scale', exact: true }).press('Enter')
  await page.getByRole('option', { name: 'Fit width', exact: true }).click()
  await page.getByRole('combobox', { name: 'Reader background', exact: true }).press('Enter')
  await page.getByRole('option', { name: 'Paper', exact: true }).click()
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(page.locator('.reader')).toHaveClass(/reader-background-paper/)
  await expect(page.locator('.reader')).toHaveClass(/reader-fit-width/)
  await page.reload()
  await expect(page.locator('.reader')).toHaveClass(/reader-background-paper/)
  await expect(page.locator('.reader')).toHaveClass(/reader-fit-width/)
  expect(server.patches.filter(p => p.fields.bookmarked === 'true')).toHaveLength(1)
})
