import { expect, test } from '@playwright/test'
import { catalogueServer } from '../helpers/catalogue-server'
import { source } from '../fixtures'
const sourcePath = `/browse/source/${source.id}`
test('source catalogue paginates, retries, searches, and returns from manga', async ({ page }) => {
  const captured = await catalogueServer(page)
  await page.goto('/browse'); await page.getByRole('link', { name: /Test source/ }).click()
  await expect(page.getByRole('link', { name: /A journey beyond/ })).toBeVisible()
  await page.getByRole('button', { name: 'Load more' }).click()
  await expect(page.getByText(/Your loaded titles are still available/)).toBeVisible()
  await expect(page.getByRole('link', { name: /A journey beyond/ })).toBeVisible()
  await page.getByRole('button', { name: 'Retry next page' }).click()
  await expect(page.getByRole('link', { name: /A second catalogue/ })).toBeVisible()
  await expect(page.locator('.manga-card')).toHaveCount(2)
  await page.getByRole('tab', { name: 'Latest', exact: true }).click()
  await expect(page.getByRole('link', { name: /Latest title/ })).toBeVisible()
  await page.getByLabel('Search source').fill('stars & moon')
  await page.getByRole('button', { name: 'Search catalogue' }).click()
  await expect(page.getByRole('link', { name: /Search result/ })).toBeVisible()
  expect(captured.requests.some(r => new URL(r, 'http://test').searchParams.get('searchTerm') === 'stars & moon')).toBe(true)
  await page.getByRole('link', { name: /Search result/ }).click()
  await expect(page.locator('.manga-detail')).toBeVisible()
  await page.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(page.getByLabel('Search source')).toHaveValue('stars & moon')
  await page.getByLabel('Search source').fill('nothing'); await page.getByLabel('Search source').press('Enter')
  await expect(page.getByRole('heading', { name: 'No titles found' })).toBeVisible()
  await page.getByRole('button', { name: 'Show popular' }).click()
  await expect(page.getByRole('link', { name: /A journey beyond/ })).toBeVisible()
  expect(captured.writes).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
test('initial failure can retry and unsupported latest does not hit endpoint', async ({ page }) => {
  const captured = await catalogueServer(page, { initialError: true, noLatest: true })
  await page.goto(sourcePath)
  await expect(page.getByRole('heading', { name: 'Source unavailable' })).toBeVisible()
  await page.getByRole('button', { name: 'Try again' }).click()
  await expect(page.locator('.manga-card')).toHaveCount(1)
  await expect(page.getByRole('tab', { name: 'Latest', exact: true })).toBeDisabled()
  await page.goto(sourcePath + '?mode=latest')
  await expect(page.getByRole('heading', { name: 'Latest updates not supported' })).toBeVisible()
  expect(captured.requests.some(r => r.includes('/latest/'))).toBe(false)
  await page.getByRole('button', { name: 'Back to sources' }).click()
  await expect(page).toHaveURL(/\/browse$/)
})
test('unknown source shows an honest missing state', async ({ page }) => {
  const captured = await catalogueServer(page)
  await page.goto('/browse/source/123')
  await expect(page.getByRole('heading', { name: 'Source not installed' })).toBeVisible()
  expect(captured.requests.some(r => r.includes('/123/popular/'))).toBe(false)
})
